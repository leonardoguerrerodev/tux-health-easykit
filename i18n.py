import os

_override = None


def set_lang(code):
    global _override
    _override = code


def lang():
    if _override:
        return _override
    v = os.environ.get("THEK_LANG")
    if v in ("es", "en"):
        return v
    for var in ("LC_ALL", "LC_MESSAGES", "LANG"):
        v = os.environ.get(var)
        if v:
            return "es" if v.lower().startswith("es") else "en"
    return "en"


def t(key, **kw):
    s = STRINGS[lang()].get(key) or STRINGS["en"].get(key) or key
    return s.format(**kw) if kw else s


